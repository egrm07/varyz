def workspace_nav(active="projects") -> str:
    links = (
        ("projects", "Projects", "/?view=dashboard"),
        ("shared", "Shared", "/account/shared"),
        ("questions", "Questions", "/account/questions"),
        ("connections", "Connections", "/?view=dashboard&section=connections"),
        ("account", "Account", "/?view=dashboard&section=account"),
    )
    return '<nav class="cloud-nav" aria-label="Cloud sections">' + ''.join(
        '<a href="' + _escape(url) + '"'
        + (' aria-current="page"' if key == active else '') + '>' + label + '</a>'
        for key, label, url in links
    ) + '</nav>'


