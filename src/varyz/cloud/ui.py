def render_storage(archive_status, report_status=None, preference_status=None):
    """Show combined accounted usage, including revisions, in one meter."""
    statuses = [
        status
        for status in (archive_status, report_status, preference_status)
        if status and (status.get("quota_bytes") or 0) > 0
    ]
    if not statuses:
        return ""
    usage = [
        max(0, status.get("bytes", 0) or 0)
        + max(0, status.get("revision_bytes", 0) or 0)
        for status in statuses
    ]
    percent = sum(usage) * 100 / sum(status["quota_bytes"] for status in statuses)
    display = f"{percent:.1f}".rstrip("0").rstrip(".")
    guidance = ""
    if percent >= 95:
        guidance = "Cloud storage is " + ("full" if percent >= 100 else "almost full") + ". "
    elif any(used >= status["quota_bytes"] for used, status in zip(usage, statuses, strict=True)):
        guidance = "Some uploads have reached a Cloud capacity limit. "
    if guidance:
        guidance = (
            '<p class="cloud-guidance">'
            + guidance
            + "Existing data remains available; pending uploads wait safely on your computer.</p>"
        )
    return (
        '<section class="cloud-storage" aria-label="Cloud storage">'
        '<h2>Cloud storage</h2><div class="cloud-storage-meter"><p>Overall '
        f'<strong>{display}% used / 100%</strong></p>'
        f'<progress max="100" value="{min(100, percent):.1f}" '
        f'aria-label="Overall Cloud storage used">{display}%</progress></div>'
        + guidance
        + "</section>"
    )


