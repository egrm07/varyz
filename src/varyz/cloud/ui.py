def form_scope(data: Mapping[str, str], previous: str = "*") -> str:
    mode = data.get("scope_mode")
    if mode is None:
        return data.get("scope", previous)
    if mode == "all":
        return "*"
    if mode != "project" or not data.get("scope_project", "").strip():
        raise ValueError("Enter a project name or choose All projects.")
    return data["scope_project"].strip()


def parse_preference_form(
    data: Mapping[str, str], current_payload: Mapping[str, Any] | None = None
) -> dict[str, Any]:
    """Convert semantic fields; caller fetches current payload and validates the wire item."""
    kind = data.get("kind")
    allowed = {
        "rule": {"statement", "kind", "scope", "domain", "rationale"},
        "answer": {"question", "answer", "scope"},
        "workflow": {"name", "steps", "scope", "domain", "rationale"},
    }
    if kind not in allowed:
        raise ValueError("Choose a supported preference type.")
    identity = data.get("id", "")
    if not re.fullmatch(r"[\w.-]{1,128}", identity):
        raise ValueError("Invalid preference identity.")
    try:
        version = int(data.get("base_version", "-1"))
    except (ValueError, TypeError):
        raise ValueError("Invalid preference version.") from None
    if version < 0:
        raise ValueError("Invalid preference version.")
    payload = {k: v for k, v in dict(current_payload or {}).items() if k in allowed[kind]}
    payload["scope"] = form_scope(data, payload.get("scope", "*"))
    fields = {
        "rule": ("statement", "domain", "rationale"),
        "answer": ("question", "answer"),
        "workflow": ("name", "domain", "rationale"),
    }[kind]
    for name in fields:
        if name in data:
            payload[name] = data[name]
    if kind == "rule" and "rule_kind" in data:
        payload["kind"] = data["rule_kind"]
    if kind == "workflow":
        indexes = {
            int(match.group(1))
            for name in data
            if (match := re.fullmatch(r"(?:step|how|optional)_(\d+)", name))
        }
        if any(index >= 20 for index in indexes):
            raise ValueError("A workflow can have up to 20 steps.")
        if indexes:
            steps = []
            for i in range(20):
                text = data.get(f"step_{i}", "").strip()
                how = data.get(f"how_{i}", "").strip()
                optional = data.get(f"optional_{i}") == "1"
                if not text:
                    if how or optional:
                        raise ValueError("Every workflow step needs a name.")
                    continue
                step: dict[str, Any] = {"step": text}
                if how:
                    step["how"] = how
                if optional:
                    step["optional"] = True
                steps.append(step)
            payload["steps"] = steps
    return {"kind": kind, "id": identity, "base_version": version, "payload": payload}
