"""Export hash-pinned cloud dependency closures from uv.lock, without local readers."""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def export(search: bool = False) -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    packages = {p["name"]: p for p in lock["package"]}
    roots = project["project"]["optional-dependencies"]["cloud"] + ["typer"]
    if search:
        roots += project["project"]["optional-dependencies"]["cloud-search"]
    todo = []
    for requirement in roots:
        match = re.match(r"([\w-]+)(?:\[([^]]+)\])?", requirement)
        assert match
        todo.append({"name": match[1], "extra": (match[2] or "").split(",")})
    required: dict[str, set[str]] = {}
    while todo:
        dependency = todo.pop()
        name = dependency["name"]
        extras = set(filter(None, dependency.get("extra", [])))
        new = extras - required.get(name, set())
        if name in required and not new:
            continue
        required.setdefault(name, set()).update(extras)
        package = packages[name]
        todo.extend(package.get("dependencies", []))
        for extra in new:
            todo.extend(package.get("optional-dependencies", {}).get(extra, []))
    lines = ["# Generated by scripts/export_cloud_requirements.py from uv.lock.\n"]
    for name in sorted(required):
        package = packages[name]
        hashes = {item["hash"] for item in package.get("wheels", [])}
        if package.get("sdist"):
            hashes.add(package["sdist"]["hash"])
        if not hashes:
            raise ValueError(f"No registry hashes for {name}")
        lines.append(name + "==" + package["version"] + " \\\n")
        values = sorted(hashes)
        for index, value in enumerate(values):
            lines.append("    --hash=" + value + (" \\\n" if index < len(values) - 1 else "\n"))
    return "".join(lines)


if __name__ == "__main__":
    for search, filename in ((False, "requirements.txt"), (True, "requirements-search.txt")):
        (ROOT / "deploy/cloud" / filename).write_text(export(search), encoding="utf-8")
